import { containerPackets, imageFormat, jpegSegments } from './metadata-writer';

/*
 * Finds the metadata that marks an image as AI-generated or AI-edited.
 *
 * Social platforms label images from two standard signals: C2PA Content Credentials and the IPTC digital source type
 * (Meta, TikTok, LinkedIn, YouTube and Google document this). Other AI metadata, such as prompts, workflow graphs,
 * generator names, and edit history, does not drive those labels but shows how the image was made.
 *
 * The same rules decide what the cleaner removes and what the verification step must no longer find.
 */

type RawMetadata = Record<string, any>;
interface FieldMatch { kind: AiSignalKind; label: string; detail: string; triggersLabel: boolean }

const latin1 = new TextDecoder('latin1');
const utf8 = new TextDecoder();
const encoder = new TextEncoder();

/** IPTC digital source types that describe generative or algorithmic content. Other values (digitalCapture...) are left alone. */
const AI_SOURCE_TYPES: Record<string, string> = {
  trainedalgorithmicmedia: 'Created with generative AI',
  compositewithtrainedalgorithmicmedia: 'Edited with generative AI',
  algorithmicmedia: 'Generated by an algorithm',
  compositesynthetic: 'Contains synthetic elements',
  algorithmicallyenhanced: 'Enhanced by an algorithm'
};

/** Names that identify AI image tools wherever they appear. */
